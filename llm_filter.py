def extract_languages(output: str) -> list[str]:
    lines = output.lower().strip().split("\n")
    lines = [line.strip() for line in lines if line.strip() != '']    
    # 1. English (en) -> group 1: English (en)
    r = r"(?:[0-9]+\.|\*) (?P<l1>[\w \(\)'\.\-,]+)|(?P<l2>english)|(?P<l3>chinese)" 
    matches = [re.search(r, line) for line in lines]
    matches = [m for m in matches if m is not None]
    # languages = [m.group(1) for m in matches if m.group(1) is not None]
    languages = []
    for g in ['l1', 'l2', 'l3']:
        languages.extend([m.group(g) for m in matches if m.group(g) is not None])
    languages = [lang.strip().lower() for lang in languages]
    languages = [lang for lang in languages if lang != '']
    languages = sorted(list(set(languages)))
    return languages

def extract_metrics(output: str) -> list[str]:
    lines = output.lower().strip().split("\n")
    lines = [line.strip() for line in lines if line.strip() != '']    
    # 1. Accuracy
    r = r"(?:[0-9]+\.|\*) (.+)"
    matches = [re.search(r, line) for line in lines]
    matches = [m for m in matches if m is not None]
    metrics = [m.group(1).strip().lower() for m in matches if m.group(1) is not None]
    metrics = sorted(list(set(metrics)))
    return metrics


def extract_units(output: str) -> list[str]:
    output = output.lower().strip()
    output = re.sub(r'\([^\(\)]*\) ?', '', output).strip() # remove parentheses with explanation
    output = re.sub(r'\.+$', '', output) # remove trailing dot
    
    if "," in output:
        output = output.split(",")        
    elif "\n" in output:
        output = output.split("\n")
    else:
        output = [output]
    items = [i.strip() for i in output]        
    items = [i.replace("and ", "") for i in items] # remove leading and
    items = [i for i in items if i != '']    
    units = sorted(list(set(items)))
    return units


def judge(system_prompt: str, user_prompt: str, items: dict[str, str], max_tokens: int = 1, local: bool = False, quant: bool = False) -> str:
    messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt.format(**items)}
    ]
    if quant:
        model_name = os.environ["QUANT_LLM_MODEL"]
        answer = _judge_quant(model_name, messages, max_new_tokens=max_tokens)
    elif local:
        model_name = os.environ["LOCAL_LLM_MODEL"]
        answer = _judge_local(model_name, messages, max_new_tokens=max_tokens)
    else:
        model_name = os.environ["LLM_MODEL"]
        answer = _judge_api(model_name, messages, max_new_tokens=max_tokens)
    return answer.strip()
    

def _judge_local(model_name: str, messages: list[dict[str, str]], max_new_tokens: int = 1) -> str:
    model = _pipeline(model_name)
    sampling_params = model.get_default_sampling_params()
    sampling_params.max_tokens = max_new_tokens
    answer = model.chat(messages, use_tqdm=False, sampling_params=sampling_params)[-1].outputs[-1].text
    return answer

def _judge_quant(model_name: str, messages: list[dict[str, str]], max_new_tokens: int = 1) -> str:
    model = _pipeline(model_name, quant=True)
    answer = model(messages, do_sample=False, max_new_tokens=max_new_tokens)[-1]['generated_text'][-1]['content'].strip()
    return answer

def _judge_api(model_name: str, messages: list[dict[str, str]], max_new_tokens: int = 1) -> str:
    headers = {
        'Authorization': f'Bearer {os.environ["LLM_TOKEN"]}',
        'Content-Type': 'application/json'
    }
    data = {
      "model": model_name,
      "messages": messages,
      "max_tokens": max_new_tokens, 
      "timeout": 600,
    }
    answer = ""
    response = requests.post(os.environ["LLM_URL"], headers=headers, json=data, timeout=600)
    if response.status_code == 200:
        answer = response.json()['choices'][0]['message']['content']        
    else:
        raise RuntimeError(f"Response error {response.status_code}: {response.text}")
    return answer


