def judge_generator(
    system_prompt: str, 
    user_prompt: str, 
    items_ds: Iterable[dict[str, str]], 
    max_tokens: int = 1, 
    local: bool = True, 
    quant: bool = True
) -> Generator[str, None, None]:
    def fmt(item_ds):
        for items in item_ds:            
            messages = [
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt.format(**items)}
            ]
            yield messages    
    
    if quant:
        model_name = os.environ["QUANT_LLM_MODEL"]
        model = _pipeline(model_name, quant=True)
        for answer in model(fmt(items_ds), do_sample=False, max_new_tokens=max_tokens):
            yield answer[-1]['generated_text'][-1]['content'].strip()
    else:
        if local:
            model_name = os.environ["LOCAL_LLM_MODEL"]
            judge_fn = functools.partial(_judge_local, model_name=model_name, max_new_tokens=max_tokens)
        else:
            model_name = os.environ["LLM_MODEL"]
            judge_fn = functools.partial(_judge_api, model_name=model_name, max_new_tokens=max_tokens)
        for messages in fmt(items_ds):
            answer = judge_fn(messages=messages).strip()
            yield answer

def _get_features(items: pd.DataFrame, local: bool = True, quant: bool = True, system_prompt: str = "", user_prompt: str = "", desc: str = "", disable: bool=False) -> Generator[str, None, None]:    
    def ds_gen():
        for item in items.iloc:
            if item['exclude']:
                yield {'title': '', 'content': ''}
            else:
                md = paper_dataset.get_markdown(item['pdf_url'])
                title = item['title'] if item['title'] is not None else ''
                yield {'title': title, 'content': md}
    n = len(items)
    ds = datasets.Dataset.from_generator(ds_gen)
    
    judge_gen = judge_generator(system_prompt, user_prompt, ds, local=local, quant=quant, max_tokens=1024)
    for answer in tqdm.tqdm(judge_gen, total=n, desc=desc, disable=disable):
        yield answer

def get_units(items, local: bool = True, quant: bool = True) -> Generator[str, None, None]:
    return _get_features(items, local=local, quant=quant, system_prompt=SYSTEM_PROMPT_UNIT, user_prompt=USER_PROMPT_UNIT, desc="Units")
    
